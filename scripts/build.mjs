#!/usr/bin/env node
// scripts/build.mjs — build the static bundle from the TypeScript sources.
//
// Two halves:
//   1. host — `tsc` compiles src/ into lib/. The output is self-contained:
//      lib/index.js imports only ./core/* and ./util.js, so shipping lib/
//      alone is enough (no partial-copy hazard for the installed profile).
//   2. client — the compiled client core (lib/core/client.js) is inlined into
//      the compiled static seam (lib/client-static.js) at the __CORE__ marker;
//      the result is written to client/src/client.js (the path the dsh.client
//      scan reads) and then wrapped into the web module loader factory as
//      lib/client.js (the path package.json#exports["./client"] points at).
//
// The web profile loads browser halfs as modules wrapped in
// `window.__ModuleLoader__.load({ id, factory })` (see the shipped
// @deepseek-ai/dsh-client-* packages). The wrap below performs the equivalent
// best-effort: it inlines the source into the factory and swaps the source's
// `let react = null` fallback marker for `let react = require("react")`
// (resolved by the web module loader).
//
// ⚠️ VERIFY WITH THE WEB TOOLCHAIN before publishing: the shipped bundles are
// produced by the DSH repo's build (vite + a module map). If the loader's
// require graph differs, adjust the injected require lines here.
//
// Outputs:
//   lib/index.js, lib/core/host.js, lib/util.js   (tsc)
//   client/src/client.js                          (core inlined into the seam)
//   lib/client.js                                 (the wrapped loader module)

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const tsc = join(root, 'node_modules', 'typescript', 'bin', 'tsc')

// --- step 1: compile the sources ---------------------------------------------

execFileSync(process.execPath, [tsc, '-p', join(root, 'tsconfig.json')], { cwd: root, stdio: 'inherit' })

// --- step 2: inline the core into the seam, then wrap it ---------------------

// Inline a core: strip `export ` keywords so the factory becomes a plain
// top-level function usable inside the module body.
const inlineCore = (coreFile) => readFileSync(join(root, coreFile), 'utf8')
  .replace(/^export\s+(function|const)\s+/gm, '$1 ')
  .trim()

const seam = readFileSync(join(root, 'lib', 'client-static.js'), 'utf8')
const core = inlineCore('lib/core/client.js')
const marker = '// __CORE__'
if (!seam.includes(marker)) throw new Error('lib/client-static.js: missing ' + marker + ' marker')
const src = seam.replace(marker, core) + '\n'
writeFileSync(join(root, 'client', 'src', 'client.js'), src)
console.log('generated client/src/client.js')

// The standalone fallback line to swap for the loader's require. The swap
// must happen in place: hoisting a `require` above the `let` declaration
// throws "Cannot access 'react' before initialization" (TDZ), and keeping a
// later declaration would reset the binding back to null after the require.
// (tsc keeps the comment but terminates the statement, hence the semicolon.)
const REACT_FALLBACK = 'let react = null; // __REACT__'
if (!src.includes(REACT_FALLBACK)) {
  throw new Error(`client/src/client.js: missing the \`${REACT_FALLBACK}\` marker needed for the require swap`)
}

// Strip ESM export keywords so the source can be inlined into the factory,
// and swap the react fallback for the factory-scope require.
const body = src
  .replace(/^export\s+(const|function)\s+/gm, '$1 ')
  .replace(REACT_FALLBACK, 'let react = require("react")')
  .trim()

const wrapped = `// Generated by scripts/build.mjs — do not edit by hand.
// Source: client/src/client.js
window.__ModuleLoader__.load({
  id: "dsh-web-file-uploader",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
    ${body}
    exports.inject = inject;
    exports.apply = apply;
    return module.exports;
  }
});
`

mkdirSync(join(root, 'lib'), { recursive: true })
writeFileSync(join(root, 'lib', 'client.js'), wrapped)
console.log('built lib/client.js')

// --- step 3: drop the client-only intermediates -------------------------------
// The core and the seam live on only inside the wrapped bundle; keeping the
// raw compiled copies in lib/ would just invite editing the wrong file.

rmSync(join(root, 'lib', 'client-static.js'), { force: true })
rmSync(join(root, 'lib', 'core', 'client.js'), { force: true })
